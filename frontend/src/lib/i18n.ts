export const dictionaries: Record<Locale, Record<string, string>> = { zh, en }

export function detectLocale(language: string | undefined | null): Locale {
  return /^zh/i.test(language ?? '') ? 'zh' : 'en'
}

let current: Locale = detectLocale(globalThis.navigator?.language)

export function setLocale(l: Locale): void {
  current = l
}

export function getLocale(): Locale {
  return current
}

export function t(key: string, params?: Record<string, string | number>): string {
  const text = dictionaries[getLocale()][key]
  if (text === undefined) return key
  if (!params) return text
  return text.replace(/\{(\w+)\}/g, (match, name: string) =>
    Object.prototype.hasOwnProperty.call(params, name) ? String(params[name]) : match,
  )
}
